"""Merge results/numbers/*.json into results/numbers.json, write report/numbers.tex (one LaTeX macro per
number) and results/hypotheses.md (verdicts decided by the numbers, not by hand)."""
import json
import re
from eye2echo.style import RES, ROOT


def fmt(v):
    """Short human formatting: p-values in scientific notation, others with 2-3 significant figures."""
    if isinstance(v, str):
        return v
    if isinstance(v, int) or float(v).is_integer():
        return f'{int(v)}'
    a = abs(v)
    if a < 1e-3 and a > 0:
        m, e = f'{v:.1e}'.split('e')
        return f'{m}\\times 10^{{{int(e)}}}'
    if a < 1:
        return f'{v:.3f}' if a < 0.1 else f'{v:.2f}'
    return f'{v:.1f}' if a < 100 else f'{v:.0f}'


def macro(group, key):
    """LaTeX macro name: letters only, e.g. sim + steadyRmsOurs -> \\simSteadyRmsOurs."""
    name = group + key[0].upper() + key[1:]
    return re.sub(r'[^A-Za-z]', '', name.replace('0', 'Zero').replace('1', 'One').replace('2', 'Two')
                  .replace('3', 'Three').replace('4', 'Four').replace('5', 'Five').replace('6', 'Six')
                  .replace('7', 'Seven').replace('8', 'Eight').replace('9', 'Nine'))


def main():
    allnums = {p.stem: json.loads(p.read_text()) for p in sorted((RES / 'numbers').glob('*.json'))}
    (RES / 'numbers.json').write_text(json.dumps(allnums, indent=1))
    lines = ['% generated by scripts/collect_numbers.py from results/numbers.json; do not edit']
    for g, d in allnums.items():
        for k, v in d.items():
            lines.append(f'\\newcommand{{\\{macro(g, k)}}}{{\\ensuremath{{{fmt(v)}}}}}' if not isinstance(v, str)
                         else f'\\newcommand{{\\{macro(g, k)}}}{{{v}}}')
    (ROOT / 'report').mkdir(exist_ok=True)
    (ROOT / 'report/numbers.tex').write_text('\n'.join(lines) + '\n')

    h, s, r = allnums['human'], allnums['sim'], allnums['real']
    h1 = h['thinLowErr'] > h['fatLowErr'] and h['thinHighErr'] < 5
    h2 = s['steadyRmsOurs'] < s['steadyRmsNonpred'] and s['hTwoP'] < 0.05
    h3 = s['hiddenSlowExitOurs'] > s['hiddenSlowExitNonpred'] and s['hThreeSlowP'] < 0.05
    h3fast = s['hiddenFastExitOurs'] < s['hiddenFastExitNonpred']
    h4 = s['priorHelpsMin'] >= 20 and s['priorHurtsAt'] == 'none'
    v = lambda ok: 'supported' if ok else 'not supported'
    md = f"""# Hypotheses: outcome and deciding number (generated by scripts/collect_numbers.py)

- **H1** (thin rhombuses look diagonal when faint, fat ones do not): **{v(h1)}**. At 10% contrast the thin rhombus is off by {h['thinLowErr']:.1f} deg and the fat one by {h['fatLowErr']:.1f} deg (at 100% contrast: {h['thinHighErr']:.1f} and {h['fatHighErr']:.1f} deg); the order holds for every lambda in a 100-fold range (tests/test_weiss.py). The fit to the digitized human data is only qualitative (RMSE {h['fitRMSE']:.1f} deg).
- **H2** (steady motion: a line fit beats the last echo): **{v(h2)}**. RMS aim error {s['steadyRmsOurs']:.2f} deg [{s['steadyRmsOursLo']:.2f}, {s['steadyRmsOursHi']:.2f}] vs {s['steadyRmsNonpred']:.2f} deg [{s['steadyRmsNonpredLo']:.2f}, {s['steadyRmsNonpredHi']:.2f}], Wilcoxon Holm p = {s['hTwoP']:.1e}, r = {s['hTwoR']:.2f}, {s['nTrialsPerCell']} trials.
- **H3** (a speed change while hidden can make prediction worse): **{'mixed: supported for a slow-down, not for a speed-up' if h3 and h3fast else v(h3)}**. Target slowing 0.75 -> 0.19 m/s behind the occluder: error at reappearance {s['hiddenSlowExitOurs']:.1f} deg (line fit) vs {s['hiddenSlowExitNonpred']:.1f} deg (last echo), Holm p = {s['hThreeSlowP']:.1e}; speeding up to 3 m/s: {s['hiddenFastExitOurs']:.1f} vs {s['hiddenFastExitNonpred']:.1f} deg (prediction still better). Real bats agree for the fast change: after an occluded fast change the non-predictive model fits better (paper and here).
- **H4** (the slow prior helps only when echoes are very noisy): **{v(h4)}**. The prior lowers RMS error significantly only at noise {s['priorHelpsAt']} mm (gain {s['noise80Gain']:.2f} deg at 80 mm, {s['noise10Gain']:.3f} deg at 10 mm); it never hurts significantly. On the real head-aim data the best lambda is {r['lamOurs']:g} and held-out RSS is {r['cvOurs']:.2f} (ours) vs {r['cvPredictive']:.2f} (Salles predictive): the prior does not explain the bats' head aim better.
"""
    (RES / 'hypotheses.md').write_text(md)
    print(md)

    figs = [
        ('fig01_rhombus_contrast', 'Does a faint thin rhombus look diagonal while a fat one does not?',
         f"Yes: at 10% contrast the thin rhombus is {h['thinLowErr']:.0f} deg off and the fat one {h['fatLowErr']:.0f} deg; the order holds with lambda x0.1 and x10."),
        ('fig02_rhombus_angle_fit', 'Does the model fit one human subject (Weiss Fig. 4d, digitized)?',
         f"Only the trend: fitted lambda {h['lamFit']:.2f} (95% CI {h['lamFitLo']:.2f}-{h['lamFitHi']:.2f}), RMSE {h['fitRMSE']:.1f} deg; the human knee near 30 deg is sharper than the model's."),
        ('fig03_grating', 'Do fainter gratings look slower?',
         f"Yes: at a contrast ratio of 0.1 the relative speed is {h['gratingRelSpeedFortyAtTenth']:.2f} (max 40%) and {h['gratingRelSpeedSeventyAtTenth']:.2f} (max 70%); the model depends on absolute contrast, which Weiss et al. also report as a failure."),
        ('fig04_plaids', 'Do plaids show the Weiss effects (type II to VA, separation, contrast-ratio bias)?',
         f"Yes: type II at 5% contrast is {h['plaidTwoLowDir']:.0f} deg off (VA {h['plaidTwoVA']:.0f} deg), type I about 0; bias toward the stronger grating is smaller at higher total contrast."),
        ('fig05_param_recovery', 'Can the fitting procedure recover a known lambda?',
         f"Yes: median recovered lambda within {100 * h['recoveryMaxRelErr']:.1f}% of the true value at 2 deg noise."),
        ('fig06_sim_error_over_time', 'How does each model aim over a trial (steady, occluded, hidden speed-up)?',
         'The line fit stays on target in steady and occluded motion; the last echo lags, most at the end of the occlusion.'),
        ('fig07_sim_sweeps', 'How do occlusion length, echo noise, call rate and a hidden speed change affect each model?',
         f"Prediction wins in all sweeps except a hidden slow-down ({s['hiddenSlowExitOurs']:.0f} vs {s['hiddenSlowExitNonpred']:.0f} deg at reappearance)."),
        ('fig08_prior_gain', 'When does the slow prior help?',
         f"Only with noisy echoes: significant at {s['priorHelpsAt']} mm, saving {s['noise80Gain']:.1f} deg at 80 mm."),
        ('fig09_real_tracking', 'Do real bats aim ahead of the target (Salles Fig. 1A/1B, 3A)?',
         f"Yes: mean lead {r['leadMeanDeg']:.1f} deg, t({r['leadTrialDf']}) = {r['leadTrialT']:.2f}; {r['leadSigBins']} of {r['leadBins']} bins significant after Bonferroni."),
        ('fig10_real_models', 'Which model reproduces the bats\' head aim (Salles Fig. 2A, SI Table S1)?',
         f"Predictive (RSS {r['rssPredictive']:.2f}) and our line fit ({r['rssOurs']:.2f}) fit best, non-predictive worst ({r['rssNonpredictive']:.2f}); fixed and velocity swap order compared with the paper."),
        ('fig11_lobo_cv', 'Does the slow prior improve the fit on bats it was not tuned on?',
         f"No: held-out RSS {r['cvOurs']:.2f} (ours) vs {r['cvPredictive']:.2f} (Salles predictive) and {r['cvOursnoprior']:.2f} (no prior)."),
        ('check_digitized_fig4d', 'Do the digitized points sit on the circles of Weiss Fig. 4d?', 'Yes (red markers on the original).'),
    ]
    lines = ['# Figures: the question each answers and the takeaway (generated by scripts/collect_numbers.py)', '',
             '| Figure | Question | Takeaway |', '|---|---|---|']
    lines += [f'| `figures/{f}.png` | {q} | {t} |' for f, q, t in figs]
    (RES / 'FIGURES.md').write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
